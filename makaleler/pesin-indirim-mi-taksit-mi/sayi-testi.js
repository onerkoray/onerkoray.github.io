#!/usr/bin/env node
"use strict";
var assert = require("node:assert/strict");
var S = require("../../tools/makale-sayi.js");
var H = require("./hesap.js");
var t = S.yazi(__dirname);
var p = H.ornek();
assert.equal(H.bugunkuDeger(2000, 6, 0, 1), 12000);
assert.equal(H.bugunkuDeger(2000, 6, 0, 0), 12000);
assert.ok(Math.abs(p.esikSonrakiAy - 0.030959838) < 1e-8);
assert.ok(Math.abs(p.esikBugun - 0.044182131) < 1e-8);
assert.ok(Math.abs(H.bugunkuDeger(2000, 6, p.esikSonrakiAy, 1) - p.pesin) < 0.001);
assert.ok(Math.abs(H.bugunkuDeger(2000, 6, p.esikBugun, 0) - p.pesin) < 0.001);
assert.ok(p.ikiSonraki > p.pesin && p.dortSonraki < p.pesin && p.dortBugun > p.pesin);
assert.throws(function () { H.bugunkuDeger(-1, 6, 0.02, 1); }, RangeError);
assert.throws(function () { H.esikOran(13000, 2000, 6, 1); }, RangeError);
t.gecsin("etiket", S.tam(p.etiket) + " TL");
t.gecsin("peşin", S.tam(p.pesin) + " TL");
t.gecsin("indirim", S.tam(p.indirim) + " TL");
t.gecsin("aylık taksit", S.tam(p.taksit) + " TL");
t.gecsin("eşik sonraki ay", S.yuzde(p.esikSonrakiAy, 2));
t.gecsin("eşik bugün", S.yuzde(p.esikBugun, 2));
t.gecsin("iki yüzde bugünkü değer", S.tl(p.ikiSonraki) + " TL");
t.gecsin("iki yüzde ilk ödeme bugün", S.tl(p.ikiBugun) + " TL");
t.gecsin("dört yüzde bugünkü değer", S.tl(p.dortSonraki) + " TL");
t.gecsin("dört yüzde ilk ödeme bugün", S.tl(p.dortBugun) + " TL");
t.gecsin("dört yüzde taksit avantajı", S.tl(p.pesin - p.dortSonraki) + " TL");
t.gecsin("dört yüzde peşin avantajı", S.tl(p.dortBugun - p.pesin) + " TL");
t.bitir();
